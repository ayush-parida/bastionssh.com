import { createHash, randomBytes } from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { Transform, type Readable } from 'node:stream';
import { pipeline } from 'node:stream/promises';
import { isDeployEnvFile, type DeployAppConfig } from '@smt/shared';
import { DeployBuildError, extractTar, planBuild, type BuildPlan } from '@smt/shared/build';
import { DeployError } from '../deploy/errors.js';

/**
 * The build context of a build on the BastionSSH side (bastion-side builds
 * spec §5): the upload is written to a folder of its own under the work
 * directory, unpacked there with the same checks bastionctl makes (no
 * links leading out, no `..`, no devices, caps on size and entries),
 * environment files left out unless asked for, the Dockerfile generated by
 * the same code bastionctl uses — and the whole folder removed when the
 * build ends, however it ends. Nothing about an app outlives its build here.
 */

/** Where builds unpack (`SMT_BUILD_WORK_DIR`, else `<tmp>/smt-builds`), created owner-only. */
export function workRoot(configured: string | null): string {
  const dir = configured ?? path.join(os.tmpdir(), 'smt-builds');
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  return dir;
}

/** A fresh folder for one build, owner-only; `remove` deletes it with everything in it (safe to call twice). */
export function jobDir(root: string): { dir: string; remove: () => void } {
  const dir = fs.mkdtempSync(path.join(root, `build-${randomBytes(4).toString('hex')}-`));
  fs.chmodSync(dir, 0o700);
  return { dir, remove: () => fs.rmSync(dir, { recursive: true, force: true }) };
}

/**
 * Write the upload to `file`, refusing past `maxBytes`; returns its size
 * and SHA-256 (the release's checksum, as bastionctl computes it).
 */
export async function receiveUpload(source: Readable, file: string, maxBytes: number): Promise<{ bytes: number; sha256: string }> {
  const hash = createHash('sha256');
  let bytes = 0;
  const meter = new Transform({
    transform(chunk: Buffer, _enc, done) {
      bytes += chunk.length;
      if (bytes > maxBytes) return done(new DeployError(`The upload is larger than ${Math.round(maxBytes / 1024 ** 2)} MiB`, 413));
      hash.update(chunk);
      done(null, chunk);
    },
  });
  try {
    await pipeline(source, meter, fs.createWriteStream(file, { mode: 0o600 }));
  } catch (err) {
    fs.rmSync(file, { force: true });
    throw err;
  }
  return { bytes, sha256: hash.digest('hex') };
}

export interface PreparedContext {
  /** The folder BuildKit gets as its context (`build.dir` inside the upload). */
  dir: string;
  plan: BuildPlan;
  files: number;
  bytes: number;
  /** Environment files left out (the first 50), and how many there were. */
  skipped: string[];
  skippedCount: number;
}

/**
 * Unpack `upload` into `<into>/src` and make it a build context: refused
 * entries fail the build (DeployError 422), environment files are skipped
 * unless `includeEnvFiles`, the generated Dockerfile is written into it,
 * and what a build never needs (`.git`, `node_modules`, `.next`) removed.
 */
export async function prepareContext(
  upload: string,
  into: string,
  config: Pick<DeployAppConfig, 'build' | 'run'>,
  opts: { includeEnvFiles: boolean; maxBytes: number; buildArgs: readonly string[] },
): Promise<PreparedContext> {
  const src = path.join(into, 'src');
  try {
    const extracted = await extractTar(upload, src, { maxBytes: opts.maxBytes, ...(!opts.includeEnvFiles && { skip: isDeployEnvFile }) });
    const plan = planBuild(src, config, opts.buildArgs);
    for (const name of plan.exclude) {
      // Top-level names only, checked like every path here: never through a link out of the context
      if (name.includes('/') || name === '..') continue;
      fs.rmSync(path.join(plan.context, name), { recursive: true, force: true });
    }
    if (plan.generated) {
      const target = path.join(plan.context, plan.dockerfile);
      // A link of that name in the upload must not redirect the write
      fs.rmSync(target, { force: true });
      fs.writeFileSync(target, plan.generated, { mode: 0o644, flag: 'wx' });
    }
    return { dir: plan.context, plan, files: extracted.files, bytes: extracted.bytes, skipped: extracted.skipped, skippedCount: extracted.skippedCount };
  } catch (err) {
    if (err instanceof DeployBuildError) throw new DeployError(err.message, 422, 'build_refused');
    throw err;
  }
}
